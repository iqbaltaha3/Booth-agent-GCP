"""
Application settings.
Reads from environment variables / Secret Manager in production.
"""

from __future__ import annotations

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Read deployment and provider settings from environment variables."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    region: str = "asia-south1"

    # GCS data bucket (private, per-environment)
    gcs_data_bucket: str = "booth-agent-data-dev"

    # Local fallback for development (path to a folder that mirrors GCS layout)
    # e.g. legacy-data/ or a local copy of gs://.../gyanpur/
    local_data_root: str | None = None

    # Firebase
    # Path to service-account JSON, or leave empty to use Application Default Credentials
    firebase_credentials_path: str | None = None

    # Vertex AI Agent Engine
    agent_engine_resource_name: str | None = None
    # For local/dev: call agents in-process instead of Agent Engine
    agent_local_mode: bool = True

    # Sarvam voice
    sarvam_api_key: str = ""
    sarvam_stt_model: str = "saaras:v3"
    sarvam_stt_mode: str = "transcribe"
    sarvam_tts_model: str = "bulbul:v3"
    sarvam_tts_speaker: str = "shubh"
    sarvam_tts_pace: float = 1.0
    sarvam_tts_language: str = "hi-IN"

    # Manifest of constituencies (generated by Cloud Build, or local path)
    constituencies_manifest_path: str = "constituencies/manifest.json"


@lru_cache
def get_settings() -> Settings:
    """Load environment settings once for the process."""
    return Settings()
