"""Pydantic models validate API requests and describe responses."""

from typing import Any, Literal

from pydantic import BaseModel, Field, HttpUrl


class ChatRequest(BaseModel):
    """Accept a question, constituency, and optional conversation id."""

    question: str
    constituency_id: str
    session_id: str | None = None


class WebSource(BaseModel):
    source_id: str
    title: str
    url: HttpUrl
    published_at: str | None = None
    searched_at: str
    read_status: Literal["page_read", "snippet_only"]
    source_type: str


class ChatResponse(BaseModel):
    """Return the answer with its evidence path and timing."""

    answer: str
    charts: list[dict[str, Any]] = Field(default_factory=list)
    session_id: str
    agent_path: list[str] = Field(default_factory=list)
    latency_ms: int | None = None
    status: Literal["complete", "partial", "needs_clarification", "failed"] = "complete"
    sources: list[WebSource] = Field(default_factory=list)


class SessionHistoryResponse(BaseModel):
    """Return the saved turns for a conversation."""

    session_id: str
    turns: list[dict[str, Any]]


class PortfolioResponse(BaseModel):
    """Return a booth report and its source filename."""

    booth_name: str | None = None
    part_number: str | None = None
    portfolio: dict[str, Any]
    source_file: str | None = None


class PortfolioSearchResponse(BaseModel):
    """Return matching booth names and part numbers."""

    matches: list[dict[str, Any]]


class BoothOption(BaseModel):
    """Describe one booth in the report selector."""

    part_number: str
    booth_name: str
    region: str
    total_voters: float | None = None


class BoothRegion(BaseModel):
    """Group the booths belonging to one region."""

    region: str
    booths: list[BoothOption]


class BoothListResponse(BaseModel):
    """Return the grouped booth selector options."""

    regions: list[BoothRegion]


class TranscribeResponse(BaseModel):
    """Return recognized speech and its detected language."""

    text: str
    language: str | None = None


class SynthesizeRequest(BaseModel):
    """Accept text and optional voice preferences."""

    text: str
    language: str | None = None
    speaker: str | None = None


class VoterQueryRequest(BaseModel):
    """Accept a read-only query for one constituency."""

    sql: str = Field(..., description="SELECT-only SQL generated by the agent")
    constituency_id: str = Field(..., description="Slug; enforced against the caller's claims server-side")


class VoterQueryResponse(BaseModel):
    """Return query columns, rows, and truncation information."""

    columns: list[str]
    rows: list[list[Any]]
    row_count: int
    truncated: bool


class SchemaResponse(BaseModel):
    """Describe database tables and example category values."""

    tables: list[str]
    schema_text: str
    samples: dict


# Voter and history tools exchange the same fields, so reuse their models.
HistoryQueryRequest = VoterQueryRequest
HistoryQueryResponse = VoterQueryResponse
HistorySchemaResponse = SchemaResponse
